package io.jenkins.plugins.rust;

import hudson.FilePath;
import java.io.IOException;
import java.io.Serializable;

/**
 * Utility for generating and writing Cargo configuration files (.cargo/config.toml) for mirrors and registries.
 */
public final class CargoConfigUtils implements Serializable {

    private static final long serialVersionUID = 1L;

    private CargoConfigUtils() {}

    /**
     * Generates standard Cargo config content that redirects crates-io to a corporate mirror.
     *
     * @param mirrorUrl URL of the crates mirror (e.g., Artifactory, Nexus)
     * @return Cargo config TOML content
     */
    public static String generateMirrorConfig(String mirrorUrl) {
        if (mirrorUrl == null || mirrorUrl.isBlank()) {
            return "";
        }
        String cleanUrl = mirrorUrl.trim();
        String registryEntry;
        if (cleanUrl.startsWith("sparse+") || cleanUrl.startsWith("http://") || cleanUrl.startsWith("https://")) {
            if (!cleanUrl.startsWith("sparse+") && !cleanUrl.endsWith(".git")) {
                registryEntry = "sparse+" + cleanUrl;
            } else {
                registryEntry = cleanUrl;
            }
        } else {
            registryEntry = cleanUrl;
        }

        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by Jenkins Rust Tool Plugin\n");
        sb.append("[source.crates-io]\n");
        sb.append("replace-with = \"corporate-mirror\"\n\n");
        sb.append("[source.corporate-mirror]\n");
        sb.append("registry = \"").append(registryEntry).append("\"\n");
        return sb.toString();
    }

    /**
     * Writes the mirror configuration to a specific directory (e.g. workspace or CARGO_HOME).
     */
    public static void writeConfig(FilePath baseDir, String mirrorUrl) throws IOException, InterruptedException {
        if (mirrorUrl == null || mirrorUrl.isBlank()) {
            return;
        }
        FilePath cargoDir = baseDir.child(".cargo");
        cargoDir.mkdirs();
        FilePath configFile = cargoDir.child("config.toml");
        String content = generateMirrorConfig(mirrorUrl);
        configFile.write(content, "UTF-8");
    }
}
